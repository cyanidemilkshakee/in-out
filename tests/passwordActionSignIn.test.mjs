import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { test } from "node:test";
import { Auth, customFetch } from "@auth/core";
import Keycloak from "@auth/core/providers/keycloak";

const require = createRequire(import.meta.url);
const { prepareAuthRequest } = require("../.test-dist/lib/authRequestBoundary.js");
const origin = "https://app.fixture";
const issuer = "https://identity.fixture/realms/inout";

function configuration(action) {
  return {
    basePath: "/api/auth",
    secret: "synthetic-password-action-fixture-secret",
    trustHost: true,
    session: { strategy: "jwt" },
    pages: { signIn: "/login" },
    logger: { error() {} },
    providers: [Keycloak({
      id: `keycloak-password-${action}`,
      issuer,
      clientId: "fixture-client",
      clientSecret: "synthetic-fixture-client-secret",
      checks: ["pkce", "state", "nonce"],
      [customFetch]: () => { throw new Error("Offline sign-in initiation must not contact a provider."); },
      authorization: {
        url: `${issuer}/protocol/openid-connect/auth`,
        params: { scope: "openid profile email", kc_action: "UPDATE_PASSWORD", prompt: "login", max_age: "0" },
      },
    })],
  };
}

async function csrf(action) {
  const response = await Auth(new Request(`${origin}/api/auth/csrf`), configuration(action));
  assert.equal(response.status, 200);
  const { csrfToken } = await response.json();
  assert.equal(typeof csrfToken, "string");
  return {
    csrfToken,
    cookie: response.headers.getSetCookie().map((cookie) => cookie.split(";")[0]).join("; "),
  };
}

function signInRequest(action, csrfState, fields = {}, query = "") {
  return new Request(`${origin}/api/auth/signin/keycloak-password-${action}${query}`, {
    method: "POST",
    headers: {
      Origin: origin,
      Cookie: csrfState.cookie ?? "",
      "Content-Type": "application/x-www-form-urlencoded",
      "X-Auth-Return-Redirect": "1",
    },
    body: new URLSearchParams({ csrfToken: csrfState.csrfToken ?? "", callbackUrl: "/admin", ...fields }),
  });
}

async function boundedAuth(request, action) {
  const boundary = await prepareAuthRequest(request, origin);
  return Auth(new Request(request.url, {
    method: request.method,
    headers: request.headers,
    body: boundary.body,
  }), configuration(action));
}

function checkCookieNames(response) {
  return response.headers.getSetCookie().map((cookie) => cookie.split("=")[0]);
}

for (const action of ["setup", "change"]) {
  test(`${action}: CSRF-protected POST starts the fixed password action with PKCE, state and nonce`, async () => {
    const state = await csrf(action);
    const callbackUrl = action === "setup" ? "/admin" : "/account?passwordChange=complete";
    const response = await boundedAuth(signInRequest(action, state, { callbackUrl }), action);
    assert.equal(response.status, 200);
    const destination = new URL((await response.json()).url);
    assert.equal(destination.origin, new URL(issuer).origin);
    assert.equal(destination.pathname, "/realms/inout/protocol/openid-connect/auth");
    for (const [key, value] of Object.entries({
      kc_action: "UPDATE_PASSWORD", prompt: "login", max_age: "0", response_type: "code",
      client_id: "fixture-client", scope: "openid profile email", code_challenge_method: "S256",
      redirect_uri: `${origin}/api/auth/callback/keycloak-password-${action}`,
    })) assert.equal(destination.searchParams.get(key), value, key);
    for (const key of ["code_challenge", "state", "nonce"]) {
      assert.ok(destination.searchParams.get(key), `${key} must be generated by Auth.js`);
    }
    const cookies = checkCookieNames(response);
    for (const suffix of ["state", "pkce.code_verifier", "nonce"]) {
      assert.ok(cookies.includes(`__Secure-authjs.${suffix}`), `${suffix} must have an encrypted callback cookie`);
    }
    assert.ok(cookies.every((name) => !name.includes("session-token")), "Starting a password action cannot establish a session");
  });

  test(`${action}: absent or mismatched CSRF evidence cannot start a provider redirect`, async () => {
    const valid = await csrf(action);
    for (const state of [{}, { cookie: valid.cookie }, { csrfToken: valid.csrfToken },
      { cookie: valid.cookie, csrfToken: "synthetic-mismatched-token" }]) {
      const response = await boundedAuth(signInRequest(action, state), action);
      const destination = new URL((await response.json()).url);
      assert.equal(destination.origin, origin);
      assert.equal(destination.searchParams.get("error"), "MissingCSRF");
      assert.ok(!checkCookieNames(response).some((name) => /authjs\.(?:state|nonce|pkce\.)/.test(name)));
    }
  });

  test(`${action}: the application boundary rejects external return destinations`, async () => {
    const state = await csrf(action);
    for (const callbackUrl of ["https://attacker.invalid/", "//attacker.invalid/", "/%2f/attacker.invalid/"]) {
      await assert.rejects(boundedAuth(signInRequest(action, state, { callbackUrl }), action),
        (error) => error?.status === 400);
    }
  });

  test(`${action}: browser query parameters cannot replace the configured action or OAuth security fields`, async () => {
    const state = await csrf(action);
    for (const name of ["kc_action", "redirect_uri", "client_id", "response_type", "state", "nonce", "code_challenge", "prompt", "max_age"]) {
      await assert.rejects(boundedAuth(signInRequest(action, state, {}, `?${name}=synthetic-override`), action),
        (error) => error?.status === 400);
    }
  });
}
